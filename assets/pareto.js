/* Hover/focus tooltip for the cost–quality scatter.

   The chart is inline SVG generated by build_pareto.py; every point is a
   <g class="pt"> carrying its numbers as data-* attributes, so this file needs
   no copy of the data and never falls out of sync with the plot. */

(function () {
  "use strict";

  function init() {
    var wrap = document.querySelector(".pareto-wrap");
    var tip = document.getElementById("pareto-tip");
    if (!wrap || !tip) return;

    var pts = wrap.querySelectorAll(".pt");
    if (!pts.length) return;

    function fill(pt) {
      tip.setAttribute("data-group", pt.getAttribute("data-group"));
      tip.innerHTML =
        '<p class="tip-name"><span class="sw" aria-hidden="true"></span>' +
          '<span>' + pt.getAttribute("data-label") + "</span></p>" +
        "<dl>" +
          "<dt>Overall</dt><dd>" + pt.getAttribute("data-score") + "%</dd>" +
          "<dt>Cost</dt><dd>$" + pt.getAttribute("data-cost") + "</dd>" +
        "</dl>" +
        '<p class="tip-note">' + pt.getAttribute("data-gname") + "</p>";
    }

    function place(pt) {
      // Measure in page space so it works at any responsive scale — the SVG is
      // width:100% with a fixed viewBox, so viewBox units are not CSS pixels.
      var m = pt.querySelector(".hit").getBoundingClientRect();
      var w = wrap.getBoundingClientRect();
      var x = m.left + m.width / 2 - w.left;
      var y = m.top + m.height / 2 - w.top;

      tip.style.left = "0px";
      tip.style.top = "0px";
      tip.classList.add("is-on");
      var tw = tip.offsetWidth;
      var th = tip.offsetHeight;

      // Keep the box inside the wrapper, and flip below the mark when there is
      // no room above it.
      var left = Math.min(Math.max(x, tw / 2 + 2), w.width - tw / 2 - 2);
      var below = y - th - 14 < 0;
      tip.style.left = left + "px";
      tip.style.top = (below ? y + 16 : y - 12) + "px";
      tip.style.transform = below
        ? "translate(-50%, 0)"
        : "translate(-50%, -100%)";
    }

    var active = null;

    function show(e) {
      active = e.currentTarget;
      fill(active);
      place(active);
      tip.setAttribute("aria-hidden", "false");
    }

    function hide() {
      active = null;
      tip.classList.remove("is-on");
      tip.setAttribute("aria-hidden", "true");
    }

    // Tabbing to a point can scroll it into view. Follow the mark instead of
    // dismissing, or the tooltip would never survive keyboard navigation.
    function reflow() {
      if (!active) return;
      if (active === document.activeElement) place(active);
      else hide();
    }

    pts.forEach(function (pt) {
      pt.addEventListener("mouseenter", show);
      pt.addEventListener("mouseleave", hide);
      pt.addEventListener("focus", show);
      pt.addEventListener("blur", hide);
    });

    // Touch: a tap fires mouseenter with no matching leave, so dismiss on any
    // tap that lands outside a point.
    document.addEventListener("touchstart", function (e) {
      if (!e.target.closest || !e.target.closest(".pt")) hide();
    }, { passive: true });

    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape") hide();
    });

    window.addEventListener("scroll", reflow, { passive: true });
    window.addEventListener("resize", reflow);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
